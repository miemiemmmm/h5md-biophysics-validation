"""
The registry of chemical systems the validation runs on.

Each entry names a directory under the validation dataset -- the one pointed at
by ``$H5MD_VALIDATION_DATA`` -- together with the coverage dimensions it
exercises, the protocols worth running on it, and any .mdp settings its force
field requires whatever the protocol asks for.

Nothing here builds or copies a system. The directories arrive ready to run:
topology, coordinates, any index file, already relaxed where relaxation was
needed, with every ``#include`` resolving inside the directory itself.
``prepare_system`` only names those files for grompp.

How each group was produced in the first place -- fetching a PDB entry and
solvating it, converting a .prmtop, unpacking a deposit -- is recorded in
``validation_systems/provenance/``, which the validation never invokes.
"""

