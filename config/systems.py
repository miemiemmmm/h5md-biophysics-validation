def prepare_system(system: System) -> dict:
    """Name the grompp inputs of a shipped system. Nothing is built or copied.

    Systems arrive ready: ``validation_systems/`` holds the topology, the
    coordinates and any index file, already relaxed where relaxation was
    needed, with every ``#include`` resolving inside the system's own
    directory. grompp is given explicit paths, so the depositor's filenames
    are used as they are -- ``coarsegrain.top`` stays ``coarsegrain.top``.
    """
    src = Path(system.location)
    if not src.is_dir():
        raise FileNotFoundError(
            f"{system.id}: {src} is missing. Systems are served from the "
            "directory named by $H5MD_VALIDATION_DATA; see "
            "validation_systems/provenance/ for how each group was prepared."
        )

    out = {
        "structure": src / system.structure,
        "topology": src / system.topology,
        "mdp_overrides": dict(system.mdp),
    }
    for key in ("structure", "topology"):
        if not out[key].is_file():
            raise FileNotFoundError(f"{system.id}: {out[key]} is missing")
    if system.use_index and system.index:
        index = src / system.index
        if index.is_file():
            out["index"] = index
    return out
